function wrap(categoryId, mode, raw) {
  const category = gameCategories.find(item => item.id === categoryId)
  const selected = takeTarget(raw, TARGET_PER_MODE, categoryId.length * 37 + (mode === 'relationship' ? 19 : 7))
  return selected.map((card, index) => {
    const intensity = intensityFor(mode, index)
    const text = card.text
    return {
      id: `ng750-game-${categoryId}-${mode}-${index}`,
      categoryId,
      categoryName: category.name,
      mode,
      text,
      copyText: text,
      intensity,
      stage: mode === 'relationship' ? stageFor(index) : null,
      audience: audienceFor(intensity),
      faithType: null,
      subtype: null,
      mechanic: category.mechanic,
      options: null,
      statements: null,
      responseLabels: categoryId === 'petty-or-valid' ? ['Petty','Valid','Both'] : null,
      tags: [category.name.toLowerCase(), mode, intensity.toLowerCase(), 'nigeria', 'nigeria-first', 'game'],
    }
  })
}

function customPetty(mode) {
  const situations = mode === 'friend' ? friendPetty : relationshipPetty
  const raw = []
  situations.forEach((situation, i) => pettyResponses.forEach((make, j) => raw.push({ text: make(situation), source: `${i}:${j}` })))
  return wrap('petty-or-valid', mode, raw)
}

function customLikely(mode) {
  const actions = mode === 'friend' ? friendLikely : relationshipLikely
  const frames = likelyFrames(mode)
  const raw = []
  actions.forEach((action, i) => frames.forEach((make, j) => raw.push({ text: make(action), source: `${i}:${j}` })))
  return wrap('who-is-more-likely', mode, raw)
}

export function buildNigeriaGamePrompts(categoryId, mode) {
  if (categoryId === 'petty-or-valid') return customPetty(mode)
  if (categoryId === 'who-is-more-likely') return customLikely(mode)
  return buildBaseNigeriaGamePrompts(categoryId, mode)
}

