function topicsFor(domainIds) {
  return domainIds.flatMap(domain => (ngContext[domain] || []).map(topic => ({ topic, domain, type: domainType[domain] || 'opinion' })))
}

function buildRows(categoryId, mode, topicRows, group) {
  const modeTemplates = templates[group][mode]
  const perTopic = Math.ceil((TARGET_PER_MODE + 80) / Math.max(topicRows.length, 1))
  const rows = []
  topicRows.forEach((row, topicIndex) => {
    const choices = modeTemplates[row.type] || modeTemplates.opinion
    const used = new Set()
    for (let n = 0; n < perTopic; n += 1) {
      let index = (topicIndex * 7 + n * 5 + categoryId.length) % choices.length
      let guard = 0
      while (used.has(index) && guard < choices.length) {
        index = (index + 1) % choices.length
        guard += 1
      }
      used.add(index)
      const template = choices[index]
      if (!template || template.includes('{topic feel')) continue
      rows.push({ text: template.replaceAll('{topic}', row.topic), ...row })
    }
  })
  return deterministicShuffle(rows, categoryId.length * 19 + (mode === 'relationship' ? 43 : 17))
}

function faithTypeFor(domain) {
  if (domain === 'christianLife') return 'Christian'
  if (domain === 'faithGeneral') return 'General Spirituality'
  return null
}

const cache = new Map()

export function buildNigeriaConversationPrompts(categoryId, mode) {
  const key = `${categoryId}:${mode}`
  if (cache.has(key)) return cache.get(key)
  const spec = specs[categoryId]
  const category = conversationCategories.find(item => item.id === categoryId)
  if (!spec || !category) return []

  const domains = mode === 'relationship' ? spec.relationship : spec.friend
  const rows = buildRows(categoryId, mode, topicsFor(domains), spec.group)
  const selected = takeTarget(rows, TARGET_PER_MODE, categoryId.length * 31 + (mode === 'relationship' ? 7 : 3))

  const prompts = selected.map((row, index) => {
    const intensity = intensityFor(mode, index)
    return {
      id: `ng750-${categoryId}-${mode}-${index}`,
      categoryId,
      categoryName: category.name,
      mode,
      text: row.text,
      copyText: row.text,
      intensity,
      stage: mode === 'relationship' ? stageFor(index) : null,
      audience: audienceFor(intensity),
      faithType: categoryId === 'faith-spirituality' ? faithTypeFor(row.domain) : null,
      subtype: null,
      mechanic: 'conversation',
      sourceDomain: row.domain,
      tags: [category.name.toLowerCase(), mode, intensity.toLowerCase(), 'nigeria', 'nigeria-first', row.domain.toLowerCase(), ...normalise(row.topic).split(' ').filter(word => word.length > 4).slice(0, 4)],
    }
  })

  cache.set(key, prompts)
  return prompts
}

