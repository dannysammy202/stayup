function topicsFor(domainIds) {
  return domainIds.flatMap(domain => (ngContext[domain] || []).map(topic => ({ topic, domain })))
}

function buildTextRows(categoryId, mode, topicRows, templates) {
  const rows = []
  const perTopic = Math.max(4, Math.ceil((TARGET_PER_MODE + 50) / Math.max(topicRows.length, 1)))
  topicRows.forEach((row, topicIndex) => {
    const used = new Set()
    for (let n = 0; n < perTopic; n += 1) {
      let templateIndex = (topicIndex * 7 + n * 5 + categoryId.length) % templates.length
      let guard = 0
      while (used.has(templateIndex) && guard < templates.length) {
        templateIndex = (templateIndex + 1) % templates.length
        guard += 1
      }
      used.add(templateIndex)
      const text = templates[templateIndex].replaceAll('{topic}', row.topic)
      rows.push({ text, domain: row.domain, sourceTopic: row.topic })
    }
  })
  return deterministicShuffle(rows, categoryId.length + (mode === 'relationship' ? 31 : 11))
}

function faithTypeFor(domain) {
  if (domain === 'christianLife') return 'Christian'
  if (domain === 'faithGeneral') return 'General Spirituality'
  return null
}

const cache = new Map()

export function buildNigeriaConversationPrompts(categoryId, mode) {
  const key = `${categoryId}:${mode}`
  if (cache.has(key)) return cache.get(key)
  const spec = specs[categoryId]
  const category = conversationCategories.find(item => item.id === categoryId)
  if (!spec || !category) return []

  const domains = mode === 'relationship' ? spec.relationshipDomains : spec.friendDomains
  const templates = mode === 'relationship' ? spec.relationshipTemplates : spec.friendTemplates
  const candidates = buildTextRows(categoryId, mode, topicsFor(domains), templates)
  const selected = takeTarget(candidates, TARGET_PER_MODE, categoryId.length * 13 + (mode === 'relationship' ? 5 : 2))

  const prompts = selected.map((row, index) => {
    const intensity = intensityFor(mode, index)
    const faithType = categoryId === 'faith-spirituality' ? faithTypeFor(row.domain) : null
    const audience = audienceFor(intensity)
    return {
      id: `ng750-${categoryId}-${mode}-${index}`,
      categoryId,
      categoryName: category.name,
      mode,
      text: row.text,
      copyText: row.text,
      intensity,
      stage: mode === 'relationship' ? stageFor(index) : null,
      audience,
      faithType,
      subtype: null,
      mechanic: 'conversation',
      sourceDomain: row.domain,
      tags: [
        category.name.toLowerCase(),
        mode,
        intensity.toLowerCase(),
        'nigeria',
        'nigeria-first',
        row.domain.toLowerCase(),
        ...normalise(row.sourceTopic).split(' ').filter(word => word.length > 4).slice(0, 4),
      ],
    }
  })

  cache.set(key, prompts)
  return prompts
}

